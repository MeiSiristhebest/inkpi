import { execSync, spawnSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { describe, expect, it } from 'vitest';

describe('InkPi CLI Executable Binary (bin/inkpi.js)', () => {
  const binPath = resolve(__dirname, '../bin/inkpi.js');

  it('should print version upon --version flag', () => {
    const output = execSync(`node "${binPath}" --version`, {
      encoding: 'utf8'
    });
    expect(output).toContain('InkPi v1.0.0');
  });

  it('should print help text upon --help flag', () => {
    const output = execSync(`node "${binPath}" --help`, { encoding: 'utf8' });
    expect(output).toContain('USAGE:');
    expect(output).toContain('COMMANDS:');
    expect(output).toContain('studio');
    expect(output).toContain('daemon');
    expect(output).toContain('doctor');
    expect(output).toContain('Trust a root for AGENTS files and symlink targets (repeatable)');
  });

  it('should execute doctor diagnostics', () => {
    const output = execSync(`node "${binPath}" doctor`, { encoding: 'utf8' });
    expect(output).toContain('InkPi System & Environment Diagnostics');
    expect(output).toContain('Node.js Version:');
    expect(output).toContain('SQLite Engine:');
    expect(output).toContain('Project config:');
  });

  it('reports invalid project config without hiding the remaining doctor checks', () => {
    const projectRoot = mkdtempSync(join(tmpdir(), 'inkpi doctor config-'));
    try {
      writeFileSync(join(projectRoot, 'inkpi.config.json'), JSON.stringify({ typography: { mode: 'ansi' } }));
      const result = spawnSync(process.execPath, [binPath, 'doctor'], {
        cwd: projectRoot,
        encoding: 'utf8'
      });

      expect(result.status).toBe(1);
      expect(result.stderr).toContain('typography.mode must be one of');
      expect(result.stdout).toContain('SQLite Engine:');
    } finally {
      rmSync(projectRoot, { recursive: true, force: true });
    }
  });

  it('accepts the project config generated by init from a Unicode path with spaces', () => {
    const parent = mkdtempSync(join(tmpdir(), 'inkpi init config-'));
    const projectName = '中文 workspace with spaces';
    const projectRoot = join(parent, projectName);
    try {
      const initialized = spawnSync(process.execPath, [binPath, 'init', projectName], {
        cwd: parent,
        encoding: 'utf8'
      });
      expect(initialized.status).toBe(0);

      const doctor = spawnSync(process.execPath, [binPath, 'doctor'], {
        cwd: projectRoot,
        encoding: 'utf8'
      });
      expect(doctor.status).toBe(0);
      expect(doctor.stdout).toContain('Project config:  valid');
    } finally {
      rmSync(parent, { recursive: true, force: true });
    }
  });

  it('uses project defaultModel for print mode and rejects an unknown model before provider access', () => {
    const projectRoot = mkdtempSync(join(tmpdir(), 'inkpi print config-'));
    try {
      writeFileSync(join(projectRoot, 'inkpi.config.json'), JSON.stringify({ defaultModel: 'missing-model' }));
      const env = { ...process.env };
      for (const key of [
        'DEEPSEEK_API_KEY',
        'OPENROUTER_API_KEY',
        'OPENAI_API_KEY',
        'ANTHROPIC_API_KEY',
        'GEMINI_API_KEY',
        'INKPI_MODEL_PRESET',
        'INKPI_PROVIDER',
        'INKPI_OPENAI_MODEL',
        'INKPI_DEEPSEEK_MODEL',
        'INKPI_OPENROUTER_MODEL',
        'INKPI_ANTHROPIC_MODEL',
        'INKPI_GEMINI_MODEL'
      ]) {
        delete env[key];
      }
      env.OPENAI_API_KEY = 'unused-other-provider-key';
      const result = spawnSync(process.execPath, [binPath, 'print', '--prompt', 'config probe'], {
        cwd: projectRoot,
        encoding: 'utf8',
        env
      });

      expect(result.status).toBe(1);
      expect(result.stderr).toContain("Unknown model preset or catalog model 'missing-model'");
    } finally {
      rmSync(projectRoot, { recursive: true, force: true });
    }
  });

  it('uses the project default model even when another provider key is configured', () => {
    const projectRoot = mkdtempSync(join(tmpdir(), 'inkpi model config-'));
    try {
      writeFileSync(join(projectRoot, 'inkpi.config.json'), JSON.stringify({ defaultModel: 'deepseek-chat' }));
      const env = { ...process.env };
      for (const key of [
        'DEEPSEEK_API_KEY',
        'OPENROUTER_API_KEY',
        'OPENAI_API_KEY',
        'ANTHROPIC_API_KEY',
        'GEMINI_API_KEY',
        'INKPI_MODEL_PRESET',
        'INKPI_PROVIDER',
        'INKPI_OPENAI_MODEL',
        'INKPI_DEEPSEEK_MODEL',
        'INKPI_OPENROUTER_MODEL',
        'INKPI_ANTHROPIC_MODEL',
        'INKPI_GEMINI_MODEL'
      ]) {
        delete env[key];
      }
      env.OPENAI_API_KEY = 'unused-other-provider-key';
      const result = spawnSync(process.execPath, [binPath, 'print', '--prompt', 'config probe'], {
        cwd: projectRoot,
        encoding: 'utf8',
        env
      });

      expect(result.status).toBe(1);
      expect(result.stderr).toContain("Missing API key for provider 'deepseek'");
      expect(result.stderr).not.toContain('No AI model configuration found');
    } finally {
      rmSync(projectRoot, { recursive: true, force: true });
    }
  });
});
